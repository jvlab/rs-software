function [data_out,aux_out]=rs_subset_choicesets(data_in,aux)
% [data_out,aux_out]=rs_subset_choicesets(data_in,aux)
% keeps or drops stimuli in choice data, using the Python package rs_tools
%
% This is the companion of `rs_subset_coordsets`, for choice data (triadic or tetradic) rather than coordinates.
% The choice of stimuli is made by Python (rs_tools.subset_stimuli), from the stimulus names in data_in.typenames.
% Every trial (row of data_in.data_comp) that uses a dropped stimulus is removed, and the surviving stimuli
% are renumbered 1..N, in the order of data_out.typenames.
%
% There is no MATLAB consistency check for choice data, so problems with the contents of data_in
% (wrong number of columns, stimulus numbers that do not match the names, no trials left) are detected by Python,
% and are reported in aux_out.warnings, as for the other modules.
%
% Args:
%   data_in (struct): choice data, with fields
%
%     - data_comp (int 2-D array): choice data, one row per comparison, as returned by `rs_read_choicedata`:
%
%       - triadic (5 columns): col 1 is reference, col 2 is s1, col 3 is s2; col 4 is the number of times the first
%       difference was judged more similar than the second; col 5 is the number of times the comparison was made
%       - tetradic (6 columns): cols 1-4 are s1-s4; col 5 and col 6 are the counts, as above
%
%     - typenames (cell array): stimulus names, as returned in aux_out.typenames of `rs_read_choicedata`;
%     the stimulus numbers in the first columns of data_comp are indexes into this list.
%
%     Other fields of data_in, if any, are returned unchanged.
%
%   aux (struct): auxiliary options, may be omitted, with field
%
%     - opts_subset (struct): options for subsetting, with fields
%
%       - filter_type (char): 'keep_all' (default), 'regex', 'include', or 'exclude'
%       - filter_pattern (char or cell array): for 'regex', a regular expression, such as '^b' for names that start with b;
%       for 'include' or 'exclude', a cell array of stimulus names
%       - regex_mode (char): for 'regex', 'include' (default) to keep the stimuli that match, 'exclude' to drop them
%       - alphabetize (int): 1 to put the kept stimuli in alphabetical order, 0 (default) to keep their original order
%       - backend (char): 'auto' (default), 'py' (MATLAB's built-in Python interface, set up with pyenv), or 'cli' (command line);
%       'auto' selects 'py' in MATLAB and 'cli' in Octave
%       - python_executable (char): Python to use for 'cli'; default is 'python3'
%       - if_log (int): 1 to log progress, 0 to suppress; default is 1
%
%     - opts_check (struct): options for reporting problems, with field
%
%       - if_warn (int): 1 to show warnings, 0 to suppress; default is 1
%
% Returns:
%   data_out (struct): choice data in the same format as `data_in`, containing the kept stimuli and the trials that use only them
%
%   aux_out (struct): auxiliary outputs and parameter values used, with fields
%
%     - warnings (char): warnings generated by Python
%     - warn_bad (int): number of warnings that prevent further processing
%     - kept_indices (int 1-D array): row vector of the positions in data_in.typenames of the stimuli kept, in the order in which they appear in data_out.typenames
%     - ntrials (int 1-D array): [number of rows of data_in.data_comp, number of rows of data_out.data_comp]
%     - opts_subset (struct): aux.opts_subset, with defaults filled in
%     - opts_check (struct): aux.opts_check, with defaults filled in
%
% Note: Notes
%   -  aux may be omitted; defaults are filled in.  The default, filter_type='keep_all', returns data_in unchanged.
%   -  Python (numpy and scipy) is required, and the folder that contains this file's folder must contain rs_tools.
%   -  The counts in data_comp (the last two columns) are not changed, and so the sign convention of the counts is not changed.
%   -  For tetradic data, trials remain only if all four stimuli are kept, so a selection can leave no trials; this is reported as a warning
%   and warn_bad is set to 1.
%   -  If no stimuli remain, or the pattern is not valid, warn_bad is set to 1 and data_out is empty.
%
% Example:
%   [data_comp,aux_read]=rs_read_choicedata(fullname);
%   data_in=struct('data_comp',data_comp,'typenames',{aux_read.typenames});
%   aux=struct('opts_subset',struct('filter_type','regex','filter_pattern','^b'));
%   [data_b,aux_out]=rs_subset_choicesets(data_in,aux);
%
% See also:
%   RS_SUBSET_COORDSETS, RS_READ_CHOICEDATA, RS_ADDTREE_CHOICEDATA.
%
if (nargin<=1)
    aux=struct;
end
%set up sub-structure options
%
aux=filldefault(aux,'opts_subset',struct);
aux.opts_subset=filldefault(aux.opts_subset,'filter_type','keep_all');
aux.opts_subset=filldefault(aux.opts_subset,'filter_pattern',[]);
aux.opts_subset=filldefault(aux.opts_subset,'regex_mode','include');
aux.opts_subset=filldefault(aux.opts_subset,'alphabetize',0);
aux.opts_subset=filldefault(aux.opts_subset,'backend','auto');
aux.opts_subset=filldefault(aux.opts_subset,'python_executable','python3');
aux.opts_subset=filldefault(aux.opts_subset,'if_log',1);
%
aux=filldefault(aux,'opts_check',struct);
aux.opts_check=filldefault(aux.opts_check,'if_warn',1);
%
data_out=struct;
aux_out=struct;
aux_out.warnings=[];
aux_out.warn_bad=0;
%
% rs_tools is in the folder above the one containing the m-files
repo_root=fileparts(fileparts(mfilename('fullpath')));
%
% Python gets the choice data in the form of a file with the same variables as data_in
if ~isstruct(data_in)
    wmsg='data_in must be a structure with fields data_comp and typenames.';
    aux_out=rs_warning(wmsg,1,setfield(aux_out,'if_warn',aux.opts_check.if_warn));
else
    pyaux=struct;
    pyaux.operation='subset_choices';
    pyaux.filter_type=aux.opts_subset.filter_type;
    pyaux.filter_pattern=aux.opts_subset.filter_pattern;
    pyaux.regex_mode=aux.opts_subset.regex_mode;
    pyaux.alphabetize=aux.opts_subset.alphabetize;
    pyaux.return_indices=1;
    [data_py,wmsg]=call_python(data_in,pyaux,aux.opts_subset,repo_root);
    if ~isempty(wmsg)
        aux_out=rs_warning(wmsg,1,setfield(aux_out,'if_warn',aux.opts_check.if_warn));
    else
        aux_out.kept_indices=double(data_py.kept_indices(:))';
        data_out=rmfield(data_py,'kept_indices');
        aux_out.ntrials=[size(data_in.data_comp,1) size(data_out.data_comp,1)];
        if aux.opts_subset.if_log
            disp(sprintf('kept %3.0f of %3.0f stimuli, %5.0f of %5.0f trials',...
                length(aux_out.kept_indices),length(data_in.typenames),aux_out.ntrials(2),aux_out.ntrials(1)));
        end
    end
end
%
if aux_out.warn_bad>0
    data_out=struct;
    disp('cannot proceed');
    disp(aux_out.warnings);
end
%
aux_out.opts_subset=aux.opts_subset;
aux_out.opts_check=aux.opts_check;
return
end

function [data_py,wmsg]=call_python(data_flat,pyaux,opts_subset,repo_root)
% passes a choice-data file through rs_tools.transform, in Python, via temporary files
% wmsg is empty if all went well, and otherwise the message from Python
%
data_py=struct;
wmsg='';
backend=opts_subset.backend;
if strcmp(backend,'auto')
    if exist('OCTAVE_VERSION','builtin')
        backend='cli';
    else
        backend='py';
    end
end
tmp_in=[tempname() '.mat'];
tmp_out=[tempname() '.mat'];
tmp_aux=[tempname() '.json'];
cleanup=onCleanup(@() delete_files({tmp_in,tmp_out,tmp_aux}));
save(tmp_in,'-struct','data_flat','-v7'); %-v7 so that scipy can read the file
aux_json=jsonencode(pyaux);
%
switch backend
    case 'py'
        pe=pyenv;
        if strlength(string(pe.Version))==0
            wmsg='MATLAB has no Python configured. Set one with pyenv(''Version'',''/path/to/python''), or use opts_subset.backend=''cli''.';
            return
        end
        if count(py.sys.path,repo_root)==0
            insert(py.sys.path,int32(0),repo_root);
        end
        try
            py.rs_tools.transform.run_files(tmp_in,tmp_out,aux_json);
        catch err
            wmsg=sprintf('Python reported: %s',err.message);
            return
        end
    case 'cli'
        fid=fopen(tmp_aux,'w');
        fwrite(fid,aux_json);
        fclose(fid);
        old_pp=getenv('PYTHONPATH');
        setenv('PYTHONPATH',repo_root);
        cmd=sprintf('"%s" -m rs_tools.transform --input "%s" --output "%s" --aux-file "%s" 2>&1',...
            opts_subset.python_executable,tmp_in,tmp_out,tmp_aux);
        [status,msg]=system(cmd);
        setenv('PYTHONPATH',old_pp);
        if status~=0
            wmsg=sprintf('Python reported: %s',strtrim(msg));
            return
        end
    otherwise
        wmsg=sprintf('unknown backend ''%s'' (use ''auto'', ''py'' or ''cli'').',backend);
        return
end
data_py=load(tmp_out);
return
end

function delete_files(files)
for k=1:length(files)
    if exist(files{k},'file')
        delete(files{k});
    end
end
end
